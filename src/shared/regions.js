// 턴 숫자가 화면 어디에 있는지 — 콘텐츠별 기본 위치.
//
// 세븐나이츠 리버스는 턴을 **화면 왼쪽 위**에 `턴` 글자 아래 `16 / 70` 으로 보여준다.
// 자리가 고정이라 사람이 매번 드래그할 이유가 없어서 기본값을 넣어 둔다.
//
// 값은 **화면 대비 비율**이다 (픽셀이 아니라). 해상도가 바뀌어도, 창 크기가 바뀌어도
// 같은 자리를 가리킨다 — 1080p에서 잡은 값이 1440p·4K에서도 그대로 맞는다.
//
// ⚠ **이 값은 1920×1080 스크린샷을 눈으로 재서 넣은 것이다.** 픽셀 단위로 측정한 게
// 아니라 여유를 넉넉히 뒀다. 실제 화면에서 안 맞으면 [턴 영역]으로 다시 잡으면 되고,
// 그때 나온 값으로 여기를 고치는 게 맞다.
'use strict';

/**
 * @typedef {{fx: number, fy: number, fw: number, fh: number}} Region
 *   화면 왼쪽 위를 (0,0), 오른쪽 아래를 (1,1)로 본 비율
 */

/**
 * 파괴신·공성전 — 왼쪽 위 `턴 / 16 / 70` 자리.
 *
 * 1920×1080 기준으로 숫자 줄은 대략 **x 28~110 · y 216~248** 에 있고, 그 위에 `턴`
 * 글자(y≈165~190), 아래에 가로 막대(y≈250 언저리)가 있다. 한글이나 가로 막대가 같이
 * 들어오면 인식기가 그걸 글자 줄로 착각하므로 위쪽은 확실히 피한다.
 *
 * 아래쪽은 조금 넘겨도 괜찮게 잡았다. 막대는 얇아서 `looksLikeDigit`의 "높이 5px 미만"에
 * 걸려 글자 후보에서 빠지고, 설령 남아도 `pickLine`이 숫자 줄을 고른다. 반대로 위쪽
 * 한글은 높이가 숫자와 비슷해서 그렇게 안 걸러진다 — 그래서 위아래를 다르게 뒀다.
 *
 * 가로는 `70 / 70`(두 자리 + 슬래시 + 두 자리)까지 들어가게 넉넉히 잡았다.
 */
const DESTROYER = { fx: 0.012, fy: 0.19, fw: 0.05, fh: 0.043 };

/** 고를 수 있는 기본 위치들 — 화면의 [기본 위치] 단추가 쓴다 */
const PRESETS = [
  { id: 'destroyer', label: '파괴신·공성전 (왼쪽 위)', region: DESTROYER },
];

module.exports = { DESTROYER, PRESETS };
